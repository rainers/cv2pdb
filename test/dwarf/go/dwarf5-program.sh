set -ex
cp "$TESTDIR/dwarf5-program.go" main.go

go version
CGO_ENABLED=0 go build -ldflags=-compressdwarf=false -o go-dwarf.exe main.go
go tool nm go-dwarf.exe >go-dwarf.nm
"$CV2PDB" go-dwarf.exe go-cv.exe
"$CVDUMP" -s -l go-cv.pdb >go-cv.dump

# Procedure records have the function addresses that go tool nm reports.
text=$(awk '$3 == "runtime.text" { print $1 }' go-dwarf.nm)
for f in main.call main.main 'main.(*Value).Get'; do
  addr=$(awk -v n="$f" '$2 == "T" && $3 == n { print $1 }' go-dwarf.nm)
  off=$(printf '%08X' $((0x$addr - 0x$text)))
  awk -v a="[0001:$off]," -v n=", ${f//./@}" '$2 == "S_GPROC32:" && $3 == a && substr($0, length($0) - length(n) + 1) == n { found=1 } END {exit !found; }' go-cv.dump
done

# Procedure records of inlined functions keep their Go names, not anon_ names.
grep 'S_GPROC32: .*, main@Twice$' go-cv.dump
if grep 'S_GPROC32: .*\[anon_' go-cv.dump; then exit 1; fi

# Line records of generated code name the source file <autogenerated>, not ?.
grep -m1 '^  \.\\<autogenerated> (' go-cv.dump
if grep '^  \.\\? (' go-cv.dump; then exit 1; fi

# Variables with an empty DWARF location get no S_REGREL32 record.
mkdir -p emptyloc
cp "$TESTDIR/dwarf5-program-emptyloc.go" emptyloc/main.go

go run emptyloc/main.go go-dwarf.exe >emptyloc.txt
test -s emptyloc.txt || { echo "test precondition lost: no variable with an empty location"; exit 1; }
awk 'NR == FNR { want[$1 " " $2] = 1; next }
     $2 == "S_GPROC32:" { proc = $NF }
     $2 == "S_REGREL32:" && (proc " " $NF) in want { print; bad++ }
     END { exit bad > 0 }' emptyloc.txt go-cv.dump
